  /// Get a motivational message by index (cycles through).
  static Map<String, String> getMotivationalMessage(int dayIndex) {
    return motivationalMessages[dayIndex % motivationalMessages.length];
  }

  /// Get a tadabbur message by index (cycles through).
  static Map<String, String> getTadabburMessage(int dayIndex) {
    return tadabburMessages[dayIndex % tadabburMessages.length];
  }

  /// Get a catch-up message by index.
  static Map<String, String> getCatchUpMessage(int dayIndex) {
    return catchUpMessages[dayIndex % catchUpMessages.length];
  }

  /// Get the appropriate streak message, or null if no milestone.
  static Map<String, String>? getStreakMessage(int streak) {
    return streakMessages[streak];
  }

  /// Get a message based on notification style preference.
  static Map<String, String> getMessageForStyle(String style, int dayIndex) {
    switch (style) {
      case 'tadabbur':
        return getTadabburMessage(dayIndex);
      case 'short':
        return {
          'ar': '📖 حان وقت وردك',
          'en': '📖 Time for your daily portion',
        };
      case 'motivational':
      default:
        return getMotivationalMessage(dayIndex);
    }
  }
